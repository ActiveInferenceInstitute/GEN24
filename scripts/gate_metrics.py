#!/usr/bin/env python3
"""Generate or check ``docs/_generated/GATE_METRICS.md``.

The document has two blocks:

* **facts** - the arm list read from ``run.sh --list``, the collected test
  count (total and per file), and the interpreter used. These are
  deterministic, so ``--check`` recomputes them and fails when the committed
  document disagrees. This is the check the ``docs`` arm runs.
* **timings** - one wall-time observation per arm on this host. They are
  environment-dependent, so ``--check`` only requires the block to exist;
  ``--write`` refreshes it by running each arm through ``run.sh``.

Never hand-edit the generated file: run ``python scripts/gate_metrics.py``.

    python scripts/gate_metrics.py            # refresh facts and timings
    python scripts/gate_metrics.py --check    # facts must match, timings present
"""

import argparse
import datetime
import platform
import re
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "_generated" / "GATE_METRICS.md"
RUN_SH = ROOT / "run.sh"
FACTS_START = "<!-- gate-facts:start -->"
FACTS_END = "<!-- gate-facts:end -->"
TIMINGS_START = "<!-- gate-timings:start -->"
TIMINGS_END = "<!-- gate-timings:end -->"
COLLECTED = re.compile(r"^(\d+) tests? collected", re.MULTILINE)


def interpreter():
    """Same resolution rule as run.sh: PYTHON, then .venv, then python3."""
    candidate = ROOT / ".venv" / "bin" / "python"
    return str(candidate) if candidate.exists() else "python3"


def arms():
    result = subprocess.run(
        [str(RUN_SH), "--list"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        stdin=subprocess.DEVNULL,
        check=True,
    )
    return [line.strip() for line in result.stdout.splitlines() if line.strip()]


def collected_tests():
    """Return (total, {file: count}) from a pytest collection run."""
    result = subprocess.run(
        [interpreter(), "-m", "pytest", "tests/", "--collect-only", "-q"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        stdin=subprocess.DEVNULL,
    )
    if result.returncode != 0:
        raise SystemExit(f"pytest collection failed:\n{result.stdout}{result.stderr}")

    per_file = {}
    for line in result.stdout.splitlines():
        if "::" not in line:
            continue
        path = line.split("::", 1)[0].strip()
        # pytest prints node ids relative to its rootdir, which can be a parent
        # directory. Keep the repository-relative tail so the fact is portable.
        marker = path.find("tests/")
        if marker > 0:
            path = path[marker:]
        per_file[path] = per_file.get(path, 0) + 1

    match = COLLECTED.search(result.stdout)
    total = int(match.group(1)) if match else sum(per_file.values())
    return total, per_file


def python_version():
    """Return major.minor: patch releases are not a fact this repository fixes."""
    result = subprocess.run(
        [interpreter(), "-c", "import sys;print(f'{sys.version_info[0]}.{sys.version_info[1]}')"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        stdin=subprocess.DEVNULL,
        check=True,
    )
    return result.stdout.strip()


def render_facts(facts):
    lines = [
        FACTS_START,
        "",
        "| Fact | Value |",
        "|---|---|",
        f"| Arms (`run.sh --list`) | {', '.join(f'`{arm}`' for arm in facts['arms'])} |",
        f"| Collected tests | {facts['total']} |",
        "",
        "| Test file | Tests |",
        "|---|---|",
    ]
    for path, count in sorted(facts["per_file"].items()):
        lines.append(f"| `{path}` | {count} |")
    lines.append(FACTS_END)
    return "\n".join(lines)


def render_timings(timings, stamp, python):
    lines = [
        TIMINGS_START,
        "",
        f"Observed {stamp} on {platform.system()} {platform.machine()} with "
        f"CPython {python}, one run per arm, wall clock, warm filesystem cache.",
        "",
        "| Arm | Command | Wall time | Result |",
        "|---|---|---|---|",
    ]
    for arm, seconds, ok in timings:
        outcome = "pass" if ok else "FAIL"
        if seconds is None:
            lines.append(f"| `{arm}` | `./run.sh {arm}` | not measured | {outcome} |")
        else:
            lines.append(f"| `{arm}` | `./run.sh {arm}` | {seconds:.2f}s | {outcome} |")
    lines.append(TIMINGS_END)
    return "\n".join(lines)


def render(facts, timings, stamp):
    return "\n".join(
        [
            "# Gate metrics",
            "",
            "<!-- generated by scripts/gate_metrics.py; do not edit by hand -->",
            "",
            "Measured facts about the gate defined in [`../../run.sh`](../../run.sh).",
            "Refresh with `python scripts/gate_metrics.py`; the `docs` arm runs",
            "`python scripts/gate_metrics.py --check`, which fails when the facts",
            "block below disagrees with the repository.",
            "",
            "## Facts",
            "",
            render_facts(facts),
            "",
            "## Arm timings",
            "",
            "Timings are observations, not contracts: they change with the host,",
            "the filesystem cache and the interpreter. They are recorded so a",
            "regression in gate cost is visible, and `--check` does not re-measure",
            "them.",
            "",
            render_timings(timings, stamp, facts["python"]),
            "",
        ]
    )


def measure(arm):
    start = time.monotonic()
    result = subprocess.run(
        [str(RUN_SH), arm],
        cwd=ROOT,
        capture_output=True,
        text=True,
        stdin=subprocess.DEVNULL,
    )
    elapsed = time.monotonic() - start
    if result.returncode != 0:
        sys.stderr.write(f"arm '{arm}' failed while measuring:\n{result.stdout}{result.stderr}")
        return None, False
    return elapsed, True


def write(stamp):
    facts = {
        "arms": arms(),
        "python": python_version(),
    }
    facts["total"], facts["per_file"] = collected_tests()

    # Write the facts block first: the `docs` arm runs `--check`, which needs
    # the file to exist before the timings below are measured.
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render(facts, [], stamp), encoding="utf-8")

    timings = [(arm, *measure(arm)) for arm in facts["arms"]]
    OUTPUT.write_text(render(facts, timings, stamp), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT).as_posix()}")
    return 0


def check():
    if not OUTPUT.exists():
        print(f"FAIL: {OUTPUT.relative_to(ROOT).as_posix()} is missing; run scripts/gate_metrics.py")
        return 1

    facts = {"arms": arms()}
    facts["total"], facts["per_file"] = collected_tests()

    text = OUTPUT.read_text(encoding="utf-8")
    if FACTS_START not in text or FACTS_END not in text:
        print("FAIL: the facts block markers are missing from GATE_METRICS.md")
        return 1
    recorded = text.split(FACTS_START, 1)[1].split(FACTS_END, 1)[0]
    expected = render_facts(facts).split(FACTS_START, 1)[1].split(FACTS_END, 1)[0]
    if recorded.strip() != expected.strip():
        print("FAIL: GATE_METRICS.md facts are stale; run scripts/gate_metrics.py")
        print("--- recorded ---")
        print(recorded.strip())
        print("--- expected ---")
        print(expected.strip())
        return 1

    if TIMINGS_START not in text or TIMINGS_END not in text:
        print("FAIL: the timings block markers are missing from GATE_METRICS.md")
        return 1

    print(f"OK: gate metrics current ({facts['total']} tests, {len(facts['arms'])} arms)")
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed document instead of regenerating it",
    )
    args = parser.parse_args(argv)
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    return check() if args.check else write(stamp)


if __name__ == "__main__":
    sys.exit(main())
